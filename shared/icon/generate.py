#!/usr/bin/env python3
# Lynx Reminders app icon: three reminder rows (checkbox + line) in white glass on Ink,
# the first one done in green, like Lynx Battery's green eyes.
# Writes the Icon Composer document for Apple (layered, Liquid Glass) and the Android
# adaptive-icon drawables. Requires shapely. Run build-icons.sh, not this file directly.
import json
import pathlib
import shutil
from shapely.geometry import Point, LineString, box
from shapely.ops import unary_union

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
ICON = ROOT / "apple" / "Resources" / "AppIcon.icon"
DRAWABLE = ROOT / "android" / "app" / "src" / "main" / "res" / "drawable"
WHITE, GREEN = "#FFFFFF", "#30D158"   # green = the "green" list color: done

# Geometry on a 1000×1000 canvas: three reminder rows like the Reminders app, no frame.
# Each row is a checkbox circle and a rounded line running to the right edge.
C = 500
ROWS, R = 3, 92                        # rows, checkbox radius
PITCH = 236                            # row centre to centre
X0, X1 = 168, 852                      # left of the circles, right end of the lines
GAP = 44                               # circle to line
LINE_H = 64                            # line thickness (a pill)
RING_W, CHECK_W = 30, 32               # unchecked ring stroke, tick stroke
MITRE = dict(join_style="mitre", mitre_limit=10)


def rounded(g, r):
    return g.buffer(-r, **MITRE).buffer(r, resolution=12)


def parts(g):
    return [g] if g.geom_type == "Polygon" else list(g.geoms)


check_cells, cells = [], []
for i in range(ROWS):
    cx, cy, r = X0 + R, C + (i - (ROWS - 1) / 2) * PITCH, R
    disc = Point(cx, cy).buffer(r, resolution=64)
    if i == 0:
        tick = LineString([(cx - 0.42 * r, cy + 0.02 * r), (cx - 0.12 * r, cy + 0.32 * r), (cx + 0.44 * r, cy - 0.30 * r)])
        check_cells.append(disc.difference(tick.buffer(CHECK_W / 2, cap_style=1, join_style=1, resolution=12)))
    else:
        cells.append(disc.difference(Point(cx, cy).buffer(r - RING_W, resolution=64)))
    lx = X0 + 2 * R + GAP
    cells.append(rounded(box(lx, cy - LINE_H / 2, X1, cy + LINE_H / 2), LINE_H / 2 - 0.5))

LAYERS = [("check", check_cells, GREEN), ("cells", cells, WHITE)]  # top to bottom


def path_d(shapes, dx=0.0, dy=0.0):
    def ring(r):
        return "M" + " ".join(f"{x + dx:.1f},{y + dy:.1f}" for x, y in list(r.coords)[:-1]) + "Z"
    out = ""
    for shape in shapes:
        for p in parts(shape.simplify(0.2)):
            out += ring(p.exterior) + "".join(ring(h) for h in p.interiors)
    return out


# Centre the mark by its bounding box.
bx0, by0, bx1, by1 = unary_union([s for _, shapes, _ in LAYERS for s in shapes]).bounds
DX, DY = C - (bx0 + bx1) / 2, C - (by0 + by1) / 2

# Apple: Icon Composer document, one glass group per layer on an Ink fill, iOS + macOS.
shutil.rmtree(ICON, ignore_errors=True)
(ICON / "Assets").mkdir(parents=True)
groups = []
for name, shapes, fill in LAYERS:
    (ICON / "Assets" / f"{name}.svg").write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">'
        f'<path fill="{fill}" fill-rule="evenodd" d="{path_d(shapes, DX + 12, DY + 12)}"/></svg>\n')
    groups.append({
        "layers": [{"image-name": f"{name}.svg", "name": name, "glass": True}],
        "shadow": {"kind": "neutral", "opacity": 0.5},
        "translucency": {"enabled": True, "value": 0.4},
    })
(ICON / "icon.json").write_text(json.dumps({
    "fill": {"solid": "srgb:0.05490,0.05490,0.06275,1.00000"},   # Ink #0E0E10
    "groups": groups,
    "supported-platforms": {"squares": "shared"},
}, indent=2) + "\n")


# Android: adaptive-icon foreground (colored) and monochrome (themed icons), 66/108 safe zone.
def vector(paths):
    body = "\n".join(
        f'        <path android:fillColor="{fill}" android:fillType="evenOdd"\n            android:pathData="{d}"/>'
        for fill, d in paths)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by shared/icon/generate.py -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="1000" android:viewportHeight="1000">\n'
            '    <group android:scaleX="0.56" android:scaleY="0.56" android:pivotX="500" android:pivotY="500">\n'
            f'{body}\n    </group>\n</vector>\n')


(DRAWABLE / "ic_launcher_foreground.xml").write_text(vector(
    [(fill, path_d(shapes, DX, DY)) for _, shapes, fill in reversed(LAYERS)]))
(DRAWABLE / "ic_launcher_monochrome.xml").write_text(vector(
    [(WHITE, path_d([unary_union([s for _, shapes, _ in LAYERS for s in shapes])], DX, DY))]))
print("wrote", ICON.relative_to(ROOT), "and Android drawables")
